#!/usr/bin/env node
/* 双端统一约束。被 sync-engine 调用；任何一侧有漂移都会阻止检查通过。 */
const fs=require('fs'),path=require('path');const root=path.resolve(__dirname,'../..'),web=path.join(root,'健身网站'),mp=path.join(root,'健身小程序');
function sync(write){
 require('./port-native-content.js').sync(write);
 let drift=[];
 for(const name of ['cardio','gamify','pro','secret','coach','plan-backup','journal','plus','page-contract','records-view','diet-feedback']){
  const src=path.join(mp,'utils',name+'.js'),data=fs.readFileSync(src);
  for(const dir of [path.join(web,'shared'),path.join(mp,'cloudfunctions/webApi/lib'),path.join(mp,'cloudfunctions/sendDailyPlan/lib')]){const target=path.join(dir,name+'.js');if(!fs.existsSync(target)||!data.equals(fs.readFileSync(target))){if(write){fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(target,data)}else drift.push(path.relative(root,target))}}
 }
 const P=require(path.join(mp,'utils/presentation.js'));
 const app=JSON.parse(fs.readFileSync(path.join(mp,'app.json'),'utf8'));
 const want=P.NAV.map(n=>({pagePath:n.pagePath.slice(1),text:n.name}));
 if(JSON.stringify(app.tabBar.list)!==JSON.stringify(want)){if(write){app.tabBar.list=want;fs.writeFileSync(path.join(mp,'app.json'),JSON.stringify(app,null,2)+'\n')}else drift.push('app.json tabBar')}
 const tokens=t=>Object.keys(t).map(k=>'--'+(k==='text'?'tx':k)+':'+t[k]).join(';');
 const css='/* Generated by sync-parity.js from utils/presentation.js */\n:root{'+tokens(P.THEMES.light)+'}\nbody.dark{'+tokens(P.THEMES.dark)+'}\n';
 const target=path.join(web,'template/parity-tokens.css');if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==css){if(write)fs.writeFileSync(target,css);else drift.push('template/parity-tokens.css')}
 if(drift.length)throw new Error('双端源文件未同步：'+drift.join(', '));return true;
}
module.exports={sync};if(require.main===module){sync(process.argv.includes('--write'));console.log('双端导航、配色、秘籍及规则同步检查通过')}
