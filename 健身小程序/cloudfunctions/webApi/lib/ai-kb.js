/**
 * routine 检测：纯本地判定，命中就返回语录（0 成本），否则 null 走大模型。
 * 铁律：①危险信号（疼/痛/刺/麻/晕/伤）一律不拦 —— 伤病问题必须走详细回答；
 *      ②带疑问/求建议的一律不拦 —— 「怎么练/为什么/多少/计划/饮食/动作」都要 LLM 详细答。
 */
function routineQuote(text) {
  const t = String(text || '').trim()
  if (!t || t.length > 30) return null                 // 长文本 = 认真提问，不拦
  if (/疼|痛|刺|麻|晕|伤|不舒服|恶心/.test(t)) return null
  if (/[?？吗]|怎么|为什么|多少|该不该|能不能|计划|饮食|动作|蛋白|热量|帮我看|复盘|总结/.test(t)) return null
  const pick = arr => arr[Math.floor(Math.random() * arr.length)]
  if (/打卡|练完|训练完成|今天练了|做完了|搞定|练了/.test(t)) return pick(AI_QUOTES.train)
  if (/喝水|喝够|喝了水|补水|睡了|睡够|睡觉|睡眠|休息/.test(t)) return pick(AI_QUOTES.recovery)
  if (/升级|突破|破境/.test(t)) return pick(AI_QUOTES.breakthrough)
  return null
}

