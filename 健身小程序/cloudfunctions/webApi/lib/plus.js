/** 是否已购进阶包 */
function isPlus(user) { return !!(user && user.plus && user.plus.since) }

/** 是否已购十二周计划（¥39.9/份，按周期交付）—— 与买断包互斥：
 *  计划是周期性消耗品，塞进永久买断会产生「12 周后续版算不算」的争议，故单独按份卖 */
function hasPlan12(user) { return !!(user && user.plan12 && user.plan12.since) }

/** 重量贴齐最小配重步长 */
function snap(x, step) { const s = Number(step) > 0 ? Number(step) : 2.5; return Math.round(x / s) * s }

/**
 * 六周增力处方 —— 三阶段：积累 → 强化 → 减载+测试
 * （阶段结构参考通用力量周期原理；双渐进与组次为谭成义 × 凯圣王口径；换算用 Epley 公式）
 *
 * @param lift 动作名（展示用）
 * @param w0   自测「4×8 能标准完成」的重量 kg —— 实测优先，不让用户猜
 * @param inc  达标加重步长（杠铃默认 2.5）
 * @returns {lift, w0, inc, oneRM, target, weeks:[{w,phase,sets,reps,kg,note}]}
 *
 * 换算：自测重量 ≈ 8RM → 1RM = w × (1 + 8/30)（Epley）
 *       强化周 5×5 ≈ 6-7RM ≈ 82.5% 1RM（能撑住 5 组的强度）
 *       减载 = 组数 ×0.6、重量 ×0.8（与引擎减载口径一致）
 *       测试周目标 = 1RM × 1.05（六周自然增幅的保守预期）
 */
function strengthCycle(lift, w0, inc) {
  const w = Math.round((Number(w0) || 0) * 2) / 2
  if (!(w > 0)) return { error: '先填一个有效的自测重量（kg）——用自测四步法找到「能标准做满 8 次、最后 2 次有点勉强」的重量' }
  const step = Number(inc) > 0 ? Number(inc) : 2.5
  const oneRM = w * (1 + 8 / 30)
  const w5x5 = snap(oneRM * 0.825, step)
  const w5dl = snap(w5x5 * 0.8, 2.5)
  const target = snap(oneRM * 1.05, 2.5)
  const weeks = [
    { w: 1, phase: '积累', sets: 4, reps: '8', kg: w, note: '起点 = 你的自测重量。动作标准，每组留 2 次余力' },
    { w: 2, phase: '积累', sets: 4, reps: '10', kg: w, note: '同重量加次数 —— 双渐进第一步' },
    { w: 3, phase: '积累', sets: 4, reps: '12', kg: w, note: '能做满 4×12 → 达标。做不到就整周重做，别硬上' },
    { w: 4, phase: '强化', sets: 5, reps: '5', kg: w5x5, note: '强度周：重量上台阶、次数压到 5。最后一组应接近力竭；掉到 3 次以下就减 2.5kg' },
    { w: 5, phase: '减载', sets: 3, reps: '5', kg: w5dl, note: '组数 ×0.6、重量 ×0.8 —— 让神经恢复。减载是练得少，不是随便练' },
    { w: 6, phase: '测试', sets: 1, reps: '1RM', kg: target, note: '充分热身后单次递增冲 ' + target + 'kg。达成 = 新 1RM；下一轮以新重量重算' }
  ]
  return { lift: String(lift || '卧推'), w0: w, inc: step, oneRM: snap(oneRM, 2.5), target: target, weeks: weeks }
}

