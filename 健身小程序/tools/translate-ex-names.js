const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

function main() {
  const write = process.argv.includes('--write')
  let src = fs.readFileSync(FILE, 'utf8')
  let done = 0, missing = []
  for (const en of Object.keys(MAP)) {
    const zh = MAP[en]
    // 定位含 "name": "<en>" 的整个扁平对象
    const re = new RegExp('\\{[^{}]*?"name": "' + esc(en) + '"[^{}]*?\\}')
    const m = src.match(re)
    if (!m) { missing.push(en); continue }
    let obj = m[0]
    if (/"en": "/.test(obj)) obj = obj.replace(/"en": "[^"]*"/, '"en": "' + en + '"')
    else obj = obj.replace('"name": "' + en + '"', '"name": "' + zh + '",\n    "en": "' + en + '"')
    obj = obj.replace('"name": "' + en + '"', '"name": "' + zh + '"')
    src = src.replace(m[0], () => obj)
    done++
  }
  console.log('翻译完成: ' + done + ' / ' + Object.keys(MAP).length)
  if (missing.length) { console.log('⚠️ 未找到（名字可能已改）:\n  ' + missing.join('\n  ')) }
  // 校验：不再有纯英文名（ASCII 开头的 name）
  const lefts = (src.match(/"name": "[A-Za-z0-9][^"]*"/g) || [])
  console.log('残留英文名: ' + lefts.length + (lefts.length ? '\n  ' + lefts.join('\n  ') : ''))
  if (write && !missing.length) {
    fs.writeFileSync(FILE, src)
    console.log('✅ 已写回 ' + FILE)
  } else if (!write) {
    console.log('（干跑，加 --write 才写入）')
  }
}
main()
